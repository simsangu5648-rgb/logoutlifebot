// 책의 "오늘의 기록" 칸을 그대로 폼 입력칸으로 옮겼고, 설명은 책 본문을 그대로 싣지 않고
// 핵심만 요약했습니다(전체 내용은 책에서 읽도록 쪽수를 안내합니다).
//
// 필드 종류
//   text/textarea : 한 줄/여러 줄 입력
//   radio/checks  : 하나 고르기/여러 개 고르기 (options 배열)
//   scale         : 0~10 점수
//   number        : 숫자
//   table         : 행(rows) × 열(cols) 표. cols = [{key,label,type:'text'|'select',options}]
//   formula       : IF/THEN 쌍 (count개)
//   auto          : 앞선 기록에서 자동으로 모아 보여주는 읽기 전용 블록 (kind로 구분, rc.js에서 계산)
//   note          : 안내 문구 (입력 없음)

const T = (id, label, o = {}) => ({ type: "text", id, label, ...o });
const TA = (id, label, o = {}) => ({ type: "textarea", id, label, rows: 3, ...o });
const R = (id, label, options, o = {}) => ({ type: "radio", id, label, options, ...o });
const C = (id, label, options, o = {}) => ({ type: "checks", id, label, options, ...o });
const S = (id, label, o = {}) => ({ type: "scale", id, label, ...o });
const N = (id, label, o = {}) => ({ type: "number", id, label, ...o });
const TB = (id, label, cols, rows, o = {}) => ({ type: "table", id, label, cols, rows, ...o });
const F = (id, label, o = {}) => ({ type: "formula", id, label, count: 1, ...o });
const A = (kind, label, o = {}) => ({ type: "auto", kind, label, ...o });
const NOTE = (text) => ({ type: "note", text });

